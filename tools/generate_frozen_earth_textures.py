GLACIER = [(0x7A, 0x8E, 0xA4), (0x82, 0x96, 0xAC), (0x8A, 0x9E, 0xB4)]
POLAR = [(0x94, 0xA7, 0xBC), (0x9C, 0xAF, 0xC3)]
SEA_ICE = [(0x2C, 0x39, 0x49), (0x31, 0x3F, 0x50)]
CRACK = (0x20, 0x2A, 0x36)


def hash01(seed):
    x = seed & 0xFFFFFFFF
    x = ((x ^ (x >> 16)) * 0x45D9F3B) & 0xFFFFFFFF
    x = ((x ^ (x >> 16)) * 0x45D9F3B) & 0xFFFFFFFF
    x ^= x >> 16
    return (x & 0x00FFFFFF) / float(0x01000000)


def is_land(lat, lon):
    if lat < -66 + 3 * math.sin(math.radians(lon) * 3) + 2 * math.sin(math.radians(lon) * 7 + 2):
        return True
    row = min(71, max(0, int((90 - lat) / 2.5)))
    col = int(((lon + 180) % 360) / 2.5) % 144
    return LAND[row][col] == '#'


def pick(palette, seed):
    return palette[int(hash01(seed) * len(palette)) % len(palette)]


def texel_color(lat, lon, seed):
    if is_land(lat, lon):
        return pick(POLAR if abs(lat) > 62 else GLACIER, seed)
    if hash01(seed + 11) < 0.04:
        return CRACK
    return pick(SEA_ICE, seed)


def main():
    w, h = 144 * TEXELS_PER_CELL, 72 * TEXELS_PER_CELL
    im = Image.new('RGBA', (w, h))
    for y in range(h):
        lat = 90 - (y + 0.5) * 180 / h
        for x in range(w):
            lon = -180 + (x + 0.5) * 360 / w
            im.putpixel((x, y), texel_color(lat, lon, y * 7919 + x * 104_729) + (255,))
    im.save(OUT)
    print(OUT)


if __name__ == '__main__':
    main()
